(function (root, factory) {
  if (typeof module !== 'undefined' && module.exports) module.exports = factory(require('./cvd-core.js'));
  else root.GLBCore = factory(typeof CVD !== 'undefined' ? CVD : root.CVD); // CVD is a global const in the page
})(typeof self !== 'undefined' ? self : this, function (CVD) {
  'use strict';
  const VERSION = '0.2.0';

  // Names that modelling software generates (3ds Max, Babylon exporter, Blender defaults).
  const GENERIC = /^(?:\d*\s*-\s*)?(?:V\d*)?(?:Cone|Cyl|Cylinder|Sph|Sphere|Box|Circle|Torus|Plane|Mesh|Object|Group|Grp|Xfm|Mtl|Text|Line|Omni|Default|Material|Node|PART\d*|TRANSPARENT_PARTS|INITIAL_TRANSPARENT|Teapot|Geosphere|Capsule|Tube|Shape|Cube|Icosphere|UVSphere)[\s_#.\-]*\d*(?:[_\-]?FACES\d*)?(?:_\d+)?$/i;
  const GENERIC_MATERIAL = /^\d+\s*-\s*Default$/i;
  // 3ds Max text shapes are exported as nodes named Text…; the Babylon exporter may give their mesh
  // a different name (e.g. PART1_3) under a Text… parent, so the parent name is checked too.
  const TEXTGEO = /^(?:V\d*)?Text\d*/i;

  const RULES = {
    softwareName: 'node name empty or matching the pattern of names generated by modelling software (GENERIC)',
    textAsGeometry: 'geometry-bearing node whose own, mesh or parent name starts with "Text" (3ds Max text shape)',
    described: 'node or mesh has extras.a11y.label or extras.a11y.description',
    colour: 'material baseColorFactor (linear) converted to sRGB; texture, lighting and tone mapping not modelled',
    alpha: 'opacity used only when alphaMode is BLEND (glTF 2.0); MASK and OPAQUE are drawn opaque',
    defaultMaterial: 'primitive without material uses the glTF default material (white, opaque)'
  };

  const MAGIC_GLTF = 0x46546C67, CHUNK_JSON = 0x4E4F534A;

  function parse(buffer) {
    const ab = buffer instanceof ArrayBuffer ? buffer : buffer.buffer.slice(buffer.byteOffset, buffer.byteOffset + buffer.byteLength);
    const dv = new DataView(ab);
    if (ab.byteLength >= 20 && dv.getUint32(0, true) === MAGIC_GLTF) {
      const version = dv.getUint32(4, true);
      if (version !== 2) throw Error('Only glTF 2.0 is supported (this file is version ' + version + ').');
      const len = dv.getUint32(12, true), type = dv.getUint32(16, true);
      if (type !== CHUNK_JSON) throw Error('The first chunk of the GLB is not JSON.');
      return JSON.parse(new TextDecoder().decode(new Uint8Array(ab, 20, len)));
    }
    let j;
    try { j = JSON.parse(new TextDecoder().decode(new Uint8Array(ab))); } catch (e) { throw Error('The file is not GLB or glTF.'); }
    if (!j.asset || String(j.asset.version || '').split('.')[0] !== '2') throw Error('Only glTF 2.0 is supported.');
    return j;
  }

  const linToHex = c => CVD.hex(c.slice(0, 3).map(v => 255 * CVD.encode(v)));

  function analyse(gltf) {
    const ext = gltf.extensionsUsed || [];
    const mats = (gltf.materials || []).map((m, k) => {
      const p = m.pbrMetallicRoughness || {}, f = p.baseColorFactor || [1, 1, 1, 1], e = m.extensions || {};
      const emissive = (m.emissiveFactor || [0, 0, 0]).some(x => x > 0) || !!m.emissiveTexture;
      return {
        index: k, name: m.name || '', hex: linToHex(f), alpha: f[3] ?? 1, alphaMode: m.alphaMode || 'OPAQUE',
        alphaCutoff: m.alphaMode === 'MASK' ? (m.alphaCutoff ?? 0.5) : null,
        texture: !!p.baseColorTexture, unlit: !!e.KHR_materials_unlit, emissive, transmission: !!e.KHR_materials_transmission,
        otherExtensions: Object.keys(e).filter(x => x !== 'KHR_materials_unlit' && x !== 'KHR_materials_transmission'),
        softwareName: !m.name || GENERIC.test(m.name) || GENERIC_MATERIAL.test(m.name)
      };
    });
    const DEFAULT = { index: -1, name: '(glTF default material)', hex: '#FFFFFF', alpha: 1, alphaMode: 'OPAQUE', alphaCutoff: null, texture: false, unlit: false, emissive: false, transmission: false, otherExtensions: [], softwareName: true, isDefault: true };
    const nodesIn = gltf.nodes || [], meshes = gltf.meshes || [];
    const parent = {}; nodesIn.forEach((n, i) => (n.children || []).forEach(c => { parent[c] = i; }));
    const usedMat = new Map(); let vertexColours = 0, noMaterial = 0, primitives = 0;
    const nodes = [];
    nodesIn.forEach((n, i) => {
      if (n.mesh === undefined) return;
      const mesh = meshes[n.mesh] || {};
      const own = n.name || '', meshName = mesh.name || '';
      const par = parent[i] !== undefined ? ((nodesIn[parent[i]] || {}).name || '') : '';
      const hexes = new Set(); let vc = false;
      (mesh.primitives || []).forEach(p => {
        primitives++;
        const m = p.material !== undefined && mats[p.material] ? mats[p.material] : DEFAULT;
        if (m.isDefault) noMaterial++;
        if (p.attributes && p.attributes.COLOR_0 !== undefined) { vc = true; vertexColours++; }
        hexes.add(m.hex);
        if (!usedMat.has(m)) usedMat.set(m, new Set());
        usedMat.get(m).add(i);
      });
      const a11y = (n.extras && n.extras.a11y) || (mesh.extras && mesh.extras.a11y) || null;
      nodes.push({
        index: i, name: own || '(no name)', mesh: meshName, parent: par, hexes: [...hexes],
        softwareName: !own || GENERIC.test(own),
        textAsGeometry: [own, meshName, par].some(x => x && TEXTGEO.test(x)),
        described: !!(a11y && (a11y.label || a11y.description)),
        label: a11y && a11y.label ? String(a11y.label) : '', vertexColours: vc
      });
    });
    // One row per distinct on-screen material colour (materials with the same colour are merged).
    const byHex = new Map();
    for (const [m, set] of usedMat) {
      const key = m.hex;
      const r = byHex.get(key) || { hex: key, materials: [], parts: new Set(), alpha: 1, blend: false, texture: false, unlit: false, emissive: false, mask: false };
      r.materials.push(m.name || '(no name)'); set.forEach(x => r.parts.add(x));
      if (m.alphaMode === 'BLEND') { r.blend = true; r.alpha = Math.min(r.alpha, m.alpha); }
      r.texture = r.texture || m.texture; r.unlit = r.unlit || m.unlit; r.emissive = r.emissive || m.emissive; r.mask = r.mask || m.alphaMode === 'MASK';
      byHex.set(key, r);
    }
    const colours = [...byHex.values()].map(r => ({ ...r, parts: r.parts.size })).sort((a, b) => b.parts - a.parts);
    const used = [...usedMat.keys()];
    const warnings = [];
    const w = (code, count, text) => { if (count) warnings.push({ code, count, text }); };
    w('texture', used.filter(m => m.texture).length, 'materials with a base-colour texture: their colours are not analysed');
    w('vertexColours', vertexColours, 'primitives with vertex colours (COLOR_0): the colour on screen is multiplied by them and is not analysed');
    w('emissive', used.filter(m => m.emissive).length, 'materials with emission: they look brighter than their base colour');
    w('unlit', used.filter(m => m.unlit).length, 'materials marked unlit (KHR_materials_unlit): shown with their base colour, no lighting');
    w('transmission', used.filter(m => m.transmission).length, 'materials with transmission (KHR_materials_transmission): what lies behind shows through, so the colour on screen is not the base colour');
    w('mask', used.filter(m => m.alphaMode === 'MASK').length, 'materials with alphaMode MASK: drawn opaque where alpha ≥ cutoff, invisible elsewhere');
    w('defaultMaterial', noMaterial, 'primitives without a material: the glTF default (white) is assumed');
    w('extensions', ext.length, 'extensions used: ' + ext.join(', '));
    return {
      asset: gltf.asset || {}, extensionsUsed: ext,
      counts: {
        partsWithGeometry: nodes.length, softwareNames: nodes.filter(x => x.softwareName).length,
        textAsGeometry: nodes.filter(x => x.textAsGeometry).length, described: nodes.filter(x => x.described).length,
        materials: mats.length, softwareMaterialNames: mats.filter(m => m.softwareName).length,
        materialsUsed: used.filter(m => !m.isDefault).length, distinctColours: colours.length, primitives
      },
      materials: mats, nodes, colours, warnings
    };
  }

  // Opacity blending with the background. 'srgb': on 8-bit sRGB values, as WebGL blends in an
  // sRGB-encoded default framebuffer; 'linear': in linear light, as with a linear render target.
  function blend(hex, alpha, bgHex, space) {
    const c = CVD.fromHex(hex), b = CVD.fromHex(bgHex), a = Math.max(0, Math.min(1, Number(alpha)));
    if (space === 'linear') return CVD.hex(c.map((x, i) => 255 * CVD.encode(a * CVD.decode(x / 255) + (1 - a) * CVD.decode(b[i] / 255))));
    return CVD.hex(c.map((x, i) => a * x + (1 - a) * b[i]));
  }

  // Contrast between every pair of roles (WCAG 2.2 SC 1.4.11 concerns adjacent colours).
  function roleContrasts(roles) {
    const out = [];
    for (let i = 0; i < roles.length; i++) for (let j = i + 1; j < roles.length; j++)
      out.push({ a: roles[i].label, b: roles[j].label, aHex: roles[i].hex, bHex: roles[j].hex, contrast: CVD.contrast(CVD.fromHex(roles[i].hex), CVD.fromHex(roles[j].hex)) });
    return out.sort((x, y) => x.contrast - y.contrast);
  }

  // Self-test: CIEDE2000 against Sharma, Wu & Dalal (2005), Machado matrices against the authors'
  // published table, WCAG contrast against known values, sRGB round trip.
  function selfTest(sharmaText, machadoRef) {
    const res = [];
    const rows = sharmaText.trim().split(/\r?\n/).map(s => s.trim().split(/\s+/).map(Number));
    let maxE = 0; rows.forEach(x => { maxE = Math.max(maxE, Math.abs(CVD.deltaE(x.slice(0, 3), x.slice(3, 6)) - x[6])); });
    res.push({ test: 'CIEDE2000, ' + rows.length + ' reference pairs (Sharma et al. 2005)', pass: rows.length === 34 && maxE <= 5e-5, detail: 'max |error| ' + maxE.toExponential(2) + ' (limit 5e-5, the 4-decimal rounding of the data)' });
    let maxM = 0, n = 0;
    for (const t of ['protan', 'deutan', 'tritan']) for (let s = 0; s <= 10; s++) { n++; CVD.matrix(t, s * 10).forEach((v, i) => { maxM = Math.max(maxM, Math.abs(v - machadoRef[t][s][i])); }); }
    res.push({ test: 'Machado et al. (2009) matrices, ' + n + ' of 33, against the published table', pass: n === 33 && maxM < 1e-9, detail: 'max |difference| ' + maxM });
    let rowSum = 0;
    for (const t of ['protan', 'deutan', 'tritan']) for (let s = 0; s <= 10; s++) { const m = CVD.matrix(t, s * 10); for (let r = 0; r < 3; r++) rowSum = Math.max(rowSum, Math.abs(m[3 * r] + m[3 * r + 1] + m[3 * r + 2] - 1)); }
    res.push({ test: 'Simulation keeps white and greys (row sums = 1)', pass: rowSum < 2e-6, detail: 'max |row sum − 1| ' + rowSum.toExponential(2) });
    const k = [[[0, 0, 0], [255, 255, 255], 21], [[118, 118, 118], [255, 255, 255], 4.54], [[0x77, 0x77, 0x77], [255, 255, 255], 4.48]];
    const cOk = k.every(([a, b, e]) => Math.abs(CVD.contrast(a, b) - e) < 0.005);
    res.push({ test: 'WCAG contrast: black/white 21:1, #767676/white 4.54:1, #777777/white 4.48:1', pass: cOk, detail: k.map(([a, b]) => CVD.contrast(a, b).toFixed(3)).join(', ') });
    let rt = true; for (let i = 0; i < 256; i++) if (Math.round(255 * CVD.encode(CVD.decode(i / 255))) !== i) rt = false;
    res.push({ test: 'sRGB decode/encode round trip, 256 values', pass: rt, detail: rt ? 'all equal' : 'mismatch' });
    return res;
  }

  return { VERSION, RULES, GENERIC, TEXTGEO, parse, analyse, blend, roleContrasts, selfTest, linToHex };
});
